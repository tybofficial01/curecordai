def chat_language_system(language: Language) -> str:
    """
    Build the additional system message injected alongside CHAT_SYSTEM that carries the
    patient's saved language preference - per CHAT_SYSTEM rule 4 this is only the FALLBACK/
    default (used when the current message gives no language signal), not the primary choice,
    which is the patient's own current message. Because the model may therefore reply in a
    different language than this saved preference, it's given all three disclaimer variants and
    told to close with whichever one matches the language/script it actually replied in, rather
    than one hardcoded to the saved preference.
    """
    return (
        f"The patient's saved language preference is '{language.value}' ({language_instruction(language)}) - "
        "use this ONLY as your fallback/default per rule 4, never as the primary choice when the "
        "current message's own language/script is clear.\n"
        "Always end every response with exactly one of the following disclaimers, verbatim on a "
        "new line (never translate or reword it) - the one matching the language/script you "
        "actually replied in:\n"
        f"- English reply -> {ai_disclaimer(Language.EN)}\n"
        f"- Urdu script reply -> {ai_disclaimer(Language.UR)}\n"
        f"- Roman Urdu reply -> {ai_disclaimer(Language.ROMAN_UR)}"
    )


def whatsapp_language_fallback_system(language: Language) -> str:
    """
    Compact language-fallback hint for the WhatsApp router/reply-phrasing prompts, which (unlike
    CHAT_SYSTEM) already default to matching the patient's own message directly - this is only
    needed for the rare case that message gives no real language signal to go on.
    """
    return (
        f"If the patient's message doesn't give a clear language/script to match, fall back to "
        f"their saved preference: '{language.value}' ({language_instruction(language)})."
    )



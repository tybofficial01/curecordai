# ── Language instructions ───────────────────────────────────────────────────────
# One centralized mapping used to steer every AI-generated response (chat, summaries,
# health overview) toward the patient's saved language preference. Extraction prompts
# (EXTRACTION_TEXT_SYSTEM / EXTRACTION_IMAGE_SYSTEM) intentionally do NOT use this -
# extraction is verbatim data capture from the source document, not language generation.

_COMMON_LANGUAGE_RULES = (
    "Do not switch languages unless the user explicitly requests it. Do NOT translate: "
    "drug names, medical codes, IDs, lab test identifiers, ICD/SNOMED identifiers, file "
    "names, or URLs - keep those exactly as given."
)

LANGUAGE_INSTRUCTIONS: dict[Language, str] = {
    Language.EN: (
        "Respond in clear English. " + _COMMON_LANGUAGE_RULES
    ),
    Language.UR: (
        "Respond in natural Urdu script (اردو). " + _COMMON_LANGUAGE_RULES
    ),
    Language.ROMAN_UR: (
        "Respond in natural Roman Urdu using Latin characters - NOT Urdu script. Follow "
        "natural Urdu sentence structure, but write it entirely with Latin letters. Preserve "
        "commonly-used English medical terminology as-is (e.g. keep 'Blood pressure', "
        "'Diabetes' in Latin script as commonly used by Pakistani patients) rather than "
        "force-translating every medical term. Be easy for Pakistani users to read. Avoid "
        "Urdu script entirely. " + _COMMON_LANGUAGE_RULES
    ),
}


def language_instruction(language: Language) -> str:
    """Return the natural-language instruction steering AI output toward `language`."""
    return LANGUAGE_INSTRUCTIONS[language]


